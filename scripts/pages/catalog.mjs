import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { PERMISSIONS } from "../../lib/authorization/permissions.ts";
import { PAGE_REGISTRY } from "../../lib/navigation/registry.ts";

const root = path.resolve(import.meta.dirname, "../..");
const literal = (value) => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);

export function renderPageCatalogMigration(registry = PAGE_REGISTRY) {
  const pages = [...registry].sort((left, right) => {
    // Parents are inserted before their children; the registry checker rejects cycles.
    const depth = (page) =>
      page.parentKey ? 1 + depth(registry.find((item) => item.pageKey === page.parentKey)) : 0;
    return depth(left) - depth(right) || left.pageKey.localeCompare(right.pageKey, "en");
  });
  const permissions = [...new Set(pages.map((page) => page.permission))].sort();
  const splits = pages.filter((page) => page.legacyPermission);
  const splitValues = splits
    .map(
      (page) =>
        `(${literal(page.permission)}, ${literal(page.legacyPermission)}, ${page.allowedRoles ? `array[${page.allowedRoles.map(literal).join(", ")}]::text[]` : "null::text[]"})`,
    )
    .join(",\n  ");
  const preserveExistingAccess = splits.length
    ? `
-- Preserve existing access once when splitting a shared module permission.
-- Reapplying the snapshot never overwrites a later role or individual choice.
with splits(permission_key, legacy_key, allowed_roles) as (values
  ${splitValues}
)
insert into public.role_permissions (role_key, permission_key)
select distinct previous.role_key, split.permission_key
from splits split
join newly_registered_page_permissions fresh on fresh.key = split.permission_key
join public.role_permissions previous on previous.permission_key = split.legacy_key
where split.allowed_roles is null or previous.role_key = any(split.allowed_roles)
on conflict (role_key, permission_key) do nothing;

with splits(permission_key, legacy_key, allowed_roles) as (values
  ${splitValues}
)
insert into public.user_permission_overrides (user_id, permission_key, effect, reason, granted_by)
select previous.user_id, split.permission_key, previous.effect, previous.reason, previous.granted_by
from splits split
join newly_registered_page_permissions fresh on fresh.key = split.permission_key
join public.user_permission_overrides previous on previous.permission_key = split.legacy_key
join public.user_roles assignment on assignment.user_id = previous.user_id
where split.allowed_roles is null or assignment.role_key = any(split.allowed_roles)
on conflict (user_id, permission_key) do nothing;
`
    : "";
  return `-- Generated by pnpm pages:sync from lib/navigation/registry.ts.\n-- Review and deploy through the regular migration and release gates.\n-- Existing visibility choices and user overrides are preserved.\n\nbegin;\n\nset local lock_timeout = '5s';\nset local statement_timeout = '30s';\n\nlock table public.role_permissions, public.user_permission_overrides in share row exclusive mode;\n\ncreate temporary table newly_registered_page_permissions (key text primary key) on commit drop;\n\nwith inserted as (\ninsert into public.permissions (key, description, min_level) values\n${permissions.map((key) => `  (${literal(key)}, ${literal(PERMISSIONS[key].description)}, ${PERMISSIONS[key].minLevel})`).join(",\n")}\non conflict (key) do nothing returning key\n) insert into newly_registered_page_permissions select key from inserted;\n${preserveExistingAccess}\ninsert into public.app_pages\n  (key, path, name, description, section, permission_key, parent_key, sort_order, is_navigation, is_active)\nvalues\n${pages.map((page) => `  (${[page.pageKey, page.path, page.name, page.description, page.section, page.permission, page.parentKey].map(literal).join(", ")}, ${page.sortOrder}, ${page.isNavigation && page.releaseEnabled}, ${page.releaseEnabled})`).join(",\n")}\non conflict (key) do update set\n  path = excluded.path,\n  name = excluded.name,\n  description = excluded.description,\n  section = excluded.section,\n  permission_key = excluded.permission_key,\n  parent_key = excluded.parent_key,\n  sort_order = excluded.sort_order,\n  is_navigation = excluded.is_navigation;\n\n-- New page permissions are inherited only by the two administrative roles.\n-- Existing-page splits above preserve prior module decisions. Other defaults stay unchanged.\ninsert into public.role_permissions (role_key, permission_key)\nselect role_key, permission_key\nfrom (values ('master'), ('admin')) roles(role_key)\ncross join (values ${permissions.map((key) => `(${literal(key)})`).join(", ")}) permissions(permission_key)\non conflict (role_key, permission_key) do nothing;\n\nnotify pgrst, 'reload schema';\n\ncommit;\n`;
}

export function validatePageRegistry(registry = PAGE_REGISTRY) {
  const keys = new Set();
  const paths = new Set();
  const pagePermissions = new Set();
  for (const page of registry) {
    if (!/^[a-z0-9]+([._-][a-z0-9]+)*$/.test(page.pageKey) || keys.has(page.pageKey))
      throw new Error(`Invalid or duplicate page key: ${page.pageKey}`);
    if (!/^\/(app|admin)(\/[A-Za-z0-9_-]+)*$/.test(page.path) || paths.has(page.path))
      throw new Error(`Invalid or duplicate page path: ${page.path}`);
    if (!Object.hasOwn(PERMISSIONS, page.permission))
      throw new Error(`Unknown page permission: ${page.permission}`);
    if (page.legacyPermission && !Object.hasOwn(PERMISSIONS, page.legacyPermission))
      throw new Error(`Unknown legacy page permission: ${page.legacyPermission}`);
    if (
      pagePermissions.has(page.permission) &&
      !(page.section === "simulation" && page.permission === "crm.simulators.view")
    )
      throw new Error(`Each page needs an independent permission: ${page.permission}`);
    pagePermissions.add(page.permission);
    if (
      !page.name?.trim() ||
      !page.description?.trim() ||
      !page.section?.trim() ||
      !Number.isSafeInteger(page.sortOrder) ||
      page.sortOrder < 0
    )
      throw new Error(`Incomplete page: ${page.pageKey}`);
    keys.add(page.pageKey);
    paths.add(page.path);
  }
  for (const page of registry) {
    const visited = new Set([page.pageKey]);
    let parent = page.parentKey;
    while (parent) {
      if (visited.has(parent)) throw new Error(`Page parent cycle: ${page.pageKey}`);
      const entry = registry.find((item) => item.pageKey === parent);
      if (!entry) throw new Error(`Unknown page parent: ${parent}`);
      visited.add(parent);
      parent = entry.parentKey;
    }
  }
}

// Internal shadow diagnostics intentionally have no navigation or user access control.
// These exact routes remain protected by their independent release and permission gates.
const internalRoutes = new Set([
  "/app/read-model-v3",
  "/app/read-model-v3/canal-de-parcerias",
  "/app/read-model-v3/etapas/[stage]",
  "/app/read-model-v3/ranking",
]);

export async function checkPageRoutes(repositoryRoot = root, registry = PAGE_REGISTRY) {
  const routes = [];
  async function visit(directory, parts = []) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) throw new Error("Page inventory rejects symlinks.");
      if (entry.isDirectory() && !entry.name.startsWith("_"))
        await visit(
          path.join(directory, entry.name),
          entry.name.startsWith("(") ? parts : [...parts, entry.name],
        );
      else if (/^page\.(tsx?|jsx?)$/.test(entry.name)) routes.push(`/${parts.join("/")}`);
    }
  }
  await visit(path.join(repositoryRoot, "app/(protected)"));
  for (const route of routes) {
    if (internalRoutes.has(route)) continue;
    const pattern = new RegExp(`^${route.replaceAll(/\[[^\]]+\]/g, "[^/]+")}$`);
    if (!registry.some((page) => pattern.test(page.path)))
      throw new Error(`Page missing from registry: ${route}`);
  }
  for (const page of registry) {
    if (
      !routes.some((route) =>
        new RegExp(`^${route.replaceAll(/\[[^\]]+\]/g, "[^/]+")}$`).test(page.path),
      )
    )
      throw new Error(`Registered page has no route: ${page.path}`);
  }
}

export async function checkPageCatalog(repositoryRoot = root) {
  validatePageRegistry();
  await checkPageRoutes(repositoryRoot);
  const directory = path.join(repositoryRoot, "supabase/migrations");
  const migrations = (await readdir(directory))
    .filter((name) => /_(unified|sync)_page_catalog\.sql$/.test(name))
    .sort();
  const latest = migrations.at(-1);
  const sql = renderPageCatalogMigration();
  const current = latest ? await readFile(path.join(directory, latest), "utf8") : "";
  return { directory, latest, sql, synchronized: current === sql };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await checkPageCatalog();
    if (!result.synchronized) {
      if (process.argv.includes("--check"))
        throw new Error(
          "Page catalog changed. Run pnpm pages:sync and include the generated migration.",
        );
      if (
        result.latest &&
        !(await readFile(path.join(result.directory, result.latest), "utf8")).trim()
      ) {
        await writeFile(path.join(result.directory, result.latest), result.sql);
      } else {
        const pnpmCli = process.env.npm_execpath;
        if (!pnpmCli) throw new Error("pnpm execution path is unavailable.");
        execFileSync(
          process.execPath,
          [pnpmCli, "exec", "supabase", "migration", "new", "sync_page_catalog"],
          { cwd: root, stdio: "inherit" },
        );
        const latest = (await readdir(result.directory))
          .filter((name) => name.endsWith("_sync_page_catalog.sql"))
          .sort()
          .at(-1);
        await writeFile(path.join(result.directory, latest), result.sql);
      }
    }
    console.log(`Page catalog synchronized: ${PAGE_REGISTRY.length} pages.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
